param(
    [string]$RepositoryRoot = (Resolve-Path (Join-Path $PSScriptRoot '../../..')).Path
)

$ErrorActionPreference = 'Stop'
$production = & (Join-Path $PSScriptRoot 'Build-NuGetPublishWorkflow.ps1') -RepositoryRoot $RepositoryRoot
$script:rendered = [IO.File]::ReadAllText($production)

function Replace-Contract([string]$before, [string]$after, [int]$count) {
    if (($script:rendered.Split($before).Count - 1) -ne $count) {
        throw "Publication template changed; review acceptance substitution: $before"
    }
    $script:rendered = $script:rendered.Replace($before, $after)
}

